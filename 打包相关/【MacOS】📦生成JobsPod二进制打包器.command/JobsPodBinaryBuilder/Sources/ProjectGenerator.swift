    // 计算从消费工程到二进制 SDK 根目录的相对路径。
    private static func relativePath(from baseURL: URL, to targetURL: URL) -> String {
        let baseComponents = baseURL.standardizedFileURL.pathComponents
        let targetComponents = targetURL.standardizedFileURL.pathComponents
        var sharedCount = 0
        while sharedCount < min(baseComponents.count, targetComponents.count),
              baseComponents[sharedCount] == targetComponents[sharedCount] {
            sharedCount += 1
        }
        let ups = Array(repeating: "..", count: baseComponents.count - sharedCount)
        let downs = Array(targetComponents.dropFirst(sharedCount))
        return (ups + downs).joined(separator: "/")
    }

    // 转义 Ruby 单引号字符串。
    private static func rubySingleQuoted(_ value: String) -> String {
        value
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "'", with: "\\'")
    }

    // 把字符串数组转换为 Ruby 数组字面量。
    private static func rubyArray(_ values: [String]) -> String {
        "[\(values.map { "'\(rubySingleQuoted($0))'" }.joined(separator: ", "))]"
    }

