import Foundation

enum ProjectGenerator {
    // 生成用于 CocoaPods 集成和 Pod Target 构建的临时宿主工程。
    static func writePackagingWorkspace(
        at sessionURL: URL,
        rootSpec: PodSpecRecord,
        allSpecs: [PodSpecRecord]
    ) throws {
        try FileManager.default.createDirectory(
            at: sessionURL,
            withIntermediateDirectories: true
        )
        try writeHostProject(
            at: sessionURL,
            projectName: "PackagingHost",
            sourceFileName: "AppDelegate.swift",
            sourceContents: swiftHostSource,
            sourceFileType: "sourcecode.swift",
            deploymentTarget: "12.0"
        )
        let podfile = packagingPodfile(rootSpec: rootSpec, allSpecs: allSpecs)
        try podfile.write(
            to: sessionURL.appendingPathComponent("Podfile"),
            atomically: true,
            encoding: .utf8
        )
    }

    // 生成最终二进制产物的最小消费工程。
    static func writeConsumerDemo(
        at consumerURL: URL,
        rootSpec: PodSpecRecord,
        binarySDKURL: URL
    ) throws {
        try FileManager.default.createDirectory(
            at: consumerURL,
            withIntermediateDirectories: true
        )
        let source = """
        import UIKit
        import \(rootSpec.moduleName)

        @main
        final class AppDelegate: UIResponder, UIApplicationDelegate {
            var window: UIWindow?

            func application(
                _ application: UIApplication,
                didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]? = nil
            ) -> Bool {
                let window = UIWindow(frame: UIScreen.main.bounds)
                window.rootViewController = UIViewController()
                window.makeKeyAndVisible()
                self.window = window
                return true
            }
        }
        """
        try writeHostProject(
            at: consumerURL,
            projectName: "ConsumerDemo",
            sourceFileName: "AppDelegate.swift",
            sourceContents: source,
            sourceFileType: "sourcecode.swift",
            deploymentTarget: "12.0"
        )
        let relativePath = relativePath(from: consumerURL, to: binarySDKURL)
        let podfile = """
        platform :ios, '12.0'
        project 'ConsumerDemo.xcodeproj'
        use_frameworks! :linkage => :static

        target 'ConsumerDemo' do
          pod '\(rootSpec.name)', :path => '\(rubySingleQuoted(relativePath))'
        end
        """
        try podfile.write(
            to: consumerURL.appendingPathComponent("Podfile"),
            atomically: true,
            encoding: .utf8
        )
    }

    // 生成面向二进制 SDK 的本地 podspec。
    static func binaryPodspec(
        rootSpec: PodSpecRecord,
        dependencySpecs: [PodSpecRecord],
        frameworkRelativePaths: [String],
        hasResources: Bool
    ) -> String {
        let frameworks = frameworkRelativePaths
            .map { "    '\(rubySingleQuoted($0))'" }
            .joined(separator: ",\n")
        let systemFrameworks = Array(Set(
            ([rootSpec] + dependencySpecs).flatMap(\.frameworks)
        )).sorted()
        let systemLibraries = Array(Set(
            ([rootSpec] + dependencySpecs).flatMap(\.libraries)
        )).sorted()
        let frameworksBlock = systemFrameworks.isEmpty
            ? ""
            : "\n  spec.frameworks = \(rubyArray(systemFrameworks))"
        let librariesBlock = systemLibraries.isEmpty
            ? ""
            : "\n  spec.libraries = \(rubyArray(systemLibraries))"
        let resourcesBlock = hasResources
            ? "\n  spec.resources = 'Resources/**/*'"
            : ""

        return """
        Pod::Spec.new do |spec|
          spec.name             = '\(rubySingleQuoted(rootSpec.name))'
          spec.version          = '\(rubySingleQuoted(rootSpec.version))'
          spec.summary          = '\(rubySingleQuoted(rootSpec.summary.isEmpty ? "Binary distribution for \(rootSpec.name)." : rootSpec.summary))'
          spec.description      = 'Generated by JobsPodBinaryBuilder from a user-confirmed and locked dependency graph.'
          spec.homepage         = 'https://example.local/\(rubySingleQuoted(rootSpec.name))'
          spec.license          = { :type => '\(rubySingleQuoted(rootSpec.license))' }
          spec.author           = { 'Jobs' => 'lg295060456@gmail.com' }
          spec.platform         = :ios, '12.0'
          spec.source           = { :path => '.' }
          spec.module_name      = '\(rubySingleQuoted(rootSpec.moduleName))'
          spec.vendored_frameworks = [
        \(frameworks)
          ]\(frameworksBlock)\(librariesBlock)\(resourcesBlock)
        end
        """
    }

    // 生成打包宿主使用的 Podfile，强制所有本地 Pod 使用显式路径。
    private static func packagingPodfile(
        rootSpec: PodSpecRecord,
        allSpecs: [PodSpecRecord]
    ) -> String {
        let sortedSpecs = allSpecs.sorted {
            if $0.name == rootSpec.name { return true }
            if $1.name == rootSpec.name { return false }
            return $0.name < $1.name
        }
        let podLines = sortedSpecs.map { spec -> String in
            if spec.sourceKind.isLocal {
                return "  pod '\(rubySingleQuoted(spec.name))', :path => '\(rubySingleQuoted(spec.directoryPath))'"
            }
            return "  pod '\(rubySingleQuoted(spec.name))', '= \(rubySingleQuoted(spec.version))'"
        }.joined(separator: "\n")

        return """
        source 'https://cdn.cocoapods.org/'
        platform :ios, '12.0'
        project 'PackagingHost.xcodeproj'
        install! 'cocoapods', :deterministic_uuids => true
        use_frameworks! :linkage => :static

        target 'PackagingHost' do
        \(podLines)
        end
        """
    }

    // 写入一个最小 iOS App Xcode 工程，让 CocoaPods 生成可构建的 Workspace。
    private static func writeHostProject(
        at rootURL: URL,
        projectName: String,
        sourceFileName: String,
        sourceContents: String,
        sourceFileType: String,
        deploymentTarget: String
    ) throws {
        let sourceDirectory = rootURL.appendingPathComponent(projectName, isDirectory: true)
        let projectDirectory = rootURL.appendingPathComponent("\(projectName).xcodeproj", isDirectory: true)
        try FileManager.default.createDirectory(
            at: sourceDirectory,
            withIntermediateDirectories: true
        )
        try FileManager.default.createDirectory(
            at: projectDirectory,
            withIntermediateDirectories: true
        )
        try sourceContents.write(
            to: sourceDirectory.appendingPathComponent(sourceFileName),
            atomically: true,
            encoding: .utf8
        )
        try infoPlist(bundleName: projectName).write(
            to: sourceDirectory.appendingPathComponent("Info.plist"),
            atomically: true,
            encoding: .utf8
        )
        try projectPBXProj(
            projectName: projectName,
            sourceFileName: sourceFileName,
            sourceFileType: sourceFileType,
            deploymentTarget: deploymentTarget
        ).write(
            to: projectDirectory.appendingPathComponent("project.pbxproj"),
            atomically: true,
            encoding: .utf8
        )
    }

